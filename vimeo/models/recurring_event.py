    """Information about the event owner's email quota."""

    embed: Embed3
    """The event's embed data."""

    event_type: str
    """The event type."""

    from_showcase: bool
    """Whether the event was created from a showcase."""

    from_webinar: Optional[bool] = UNSET
    """Whether the event was created from a webinar."""

    has_forced_lead_capture_form: bool
    """Whether the event has forced lead capture form enabled."""

