from __future__ import annotations

from typing import Any

from pydantic import Field
from typing_extensions import TypedDict

from ..core import SdkBaseModel
from .download1 import Download1, Download1Dict
from .enums.provenance import ProvenanceOrStr
from .enums.type11 import Type11OrStr
from .language2 import Language2, Language2Dict
from .quota import Quota, QuotaDict
from .transcode1 import Transcode1, Transcode1Dict


class AlternateAudioTrack(SdkBaseModel):
    active: bool
    """Whether the audio track is enabled."""

    download: list[Download1]
    """The downloads that are available for the audio track."""

    language: Language2
    """The language of the audio track."""

    provenance: ProvenanceOrStr
    """The origin of the audio track.

    Option descriptions:
     * ``ai_generated`` - The audio track is generated by AI.
     * ``user_uploaded`` - The audio track is uploaded by a user.
     * ``user_uploaded_and_ai_generated`` - The audio track is uploaded by a user and contains AI-generated content."""

    quota: Quota
    """The quota parameters for the audio tracks available for this version."""

    transcode: Transcode1
    """The transcode information for the audio track."""

    type_: Type11OrStr = Field(alias="type")
    """The type of audio track.

    Option descriptions:
     * ``commentary`` - The audio track is a commentary.
     * ``descriptive`` - The audio track is descriptive for accessibility.
     * ``main`` - The audio track is dubbed audio.
     * ``unknown`` - The audio track category is unknown."""

    upload: Any
    """The upload information for the audio track."""

    uri: str
    """The audio track's canonical relative URI."""


class AlternateAudioTrackDict(TypedDict):
    active: bool
    download: list[Download1 | Download1Dict]
    language: Language2 | Language2Dict
    provenance: ProvenanceOrStr
    quota: Quota | QuotaDict
    transcode: Transcode1 | Transcode1Dict
    type_: Type11OrStr
    upload: Any
    uri: str
